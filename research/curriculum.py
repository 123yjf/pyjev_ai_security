def lessons():
    marks=(("“","”"),("「","」"),('"','"'))
    for group,(topics,*classes) in enumerate(GROUPS):
        for cls,frames in zip(("mention","act","unclear"),classes):
            for j,frame in enumerate(frames):
                for i,topic in enumerate(topics):
                    l,r=marks[(i+j+group)%len(marks)]
                    yield frame.format(q=l+topic+r),cls,group,(group,cls,j)
